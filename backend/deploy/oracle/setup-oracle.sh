#!/usr/bin/env bash
# OpenLive setup for Oracle Cloud Always Free (Ubuntu 22.04 / 24.04, ARM or AMD).
#
# Run ON the Oracle instance, as root or with sudo:
#   sudo bash backend/deploy/oracle/setup-oracle.sh [your-domain.example.com]
#
# - With a domain: Caddy serves HTTPS automatically (ports 80 + 443).
# - Without a domain: Caddy serves plain HTTP on port 80.
#   The backend itself only listens on 127.0.0.1:8000 (not on the internet).
#
# Idempotent: safe to re-run after `git pull`. It never deletes the
# database (openlive.db) and never overwrites an existing admin token.
# Contains NO secrets: the admin token is generated on this machine
# and stored only in /etc/openlive/openlive.env.
set -euo pipefail

DOMAIN="${1:-}"
REPO_DIR="/opt/openlive"
BACKEND_DIR="$REPO_DIR/backend"
ENV_FILE="/etc/openlive/openlive.env"
SERVICE_FILE="/etc/systemd/system/openlive.service"

if [ "$(id -u)" -ne 0 ]; then
    echo "Please run as root or with sudo: sudo bash $0 [domain]" >&2
    exit 1
fi

# --- 1. Packages ---------------------------------------------------------
echo "[1/7] Installing packages..."
export DEBIAN_FRONTEND=noninteractive
apt-get update -y
apt-get install -y python3 python3-venv python3-full git curl ufw \
    openssl debian-keyring debian-archive-keyring apt-transport-https

# --- 2. Caddy (official repo, automatic HTTPS) ---------------------------
if ! command -v caddy >/dev/null 2>&1; then
    echo "[2/7] Installing Caddy..."
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/gpg.key' \
        | gpg --dearmor -o /usr/share/keyrings/caddy-stable-archive-keyring.gpg
    curl -1sLf 'https://dl.cloudsmith.io/public/caddy/stable/debian.deb.txt' \
        | tee /etc/apt/sources.list.d/caddy-stable.list >/dev/null
    apt-get update -y
    apt-get install -y caddy
else
    echo "[2/7] Caddy already installed, skipping."
fi

# --- 3. Code -------------------------------------------------------------
if [ -d "$REPO_DIR/.git" ]; then
    echo "[3/7] Updating code in $REPO_DIR..."
    git -C "$REPO_DIR" pull --ff-only || git -C "$REPO_DIR" pull
else
    echo "[3/7] Cloning OpenLive into $REPO_DIR..."
    git clone https://github.com/dhaouadiahmed1/openlive.git "$REPO_DIR"
fi
chown -R ubuntu:ubuntu "$REPO_DIR"

# --- 4. Python venv + dependencies ---------------------------------------
echo "[4/7] Creating virtual environment and installing requirements..."
if [ ! -d "$BACKEND_DIR/.venv" ]; then
    sudo -u ubuntu python3 -m venv "$BACKEND_DIR/.venv"
fi
sudo -u ubuntu "$BACKEND_DIR/.venv/bin/pip" install --quiet --upgrade pip
sudo -u ubuntu "$BACKEND_DIR/.venv/bin/pip" install --quiet \
    -r "$BACKEND_DIR/requirements.txt"

# --- 5. Admin token + environment file (never overwritten) ----------------
mkdir -p /etc/openlive
TOKEN_JUST_CREATED=0
if [ ! -f "$ENV_FILE" ]; then
    TOKEN="$(openssl rand -hex 32)"
    printf 'OPENLIVE_ADMIN_TOKEN=%s\nOPENLIVE_DB=%s/openlive.db\nOPENLIVE_SEED_CODE=OPENLIVE-DEMO-2026\nPORT=8000\n' \
        "$TOKEN" "$BACKEND_DIR" > "$ENV_FILE"
    TOKEN_JUST_CREATED=1
fi
chown root:ubuntu "$ENV_FILE"
chmod 640 "$ENV_FILE"

# --- 6. systemd service ---------------------------------------------------
echo "[5/7] Installing systemd service..."
cp "$BACKEND_DIR/deploy/oracle/openlive.service" "$SERVICE_FILE"
systemctl daemon-reload
systemctl enable openlive.service
systemctl restart openlive.service

# --- 7. Caddy reverse proxy + firewall ------------------------------------
echo "[6/7] Configuring Caddy..."
if [ -n "$DOMAIN" ]; then
    # Domain: automatic HTTPS. Caddy needs DNS pointing at this
    # instance *before* it can fetch a certificate.
    cat > /etc/caddy/Caddyfile <<EOF
# OpenLive — generated by setup-oracle.sh for $DOMAIN
$DOMAIN {
    reverse_proxy 127.0.0.1:8000
}
EOF
    PUBLIC_URL="https://$DOMAIN/"
else
    # No domain: plain HTTP on port 80.
    cat > /etc/caddy/Caddyfile <<'EOF'
# OpenLive — generated by setup-oracle.sh (no domain: plain HTTP on :80)
:80 {
    reverse_proxy 127.0.0.1:8000
}
EOF
    PUBLIC_IP="$(curl -fsS --max-time 10 https://ifconfig.me 2>/dev/null || hostname -I | awk '{print $1}')"
    PUBLIC_URL="http://$PUBLIC_IP/"
fi
caddy validate --config /etc/caddy/Caddyfile
systemctl enable caddy
systemctl reload caddy || systemctl restart caddy

ufw allow 22/tcp  >/dev/null 2>&1 || true
ufw allow 80/tcp  >/dev/null 2>&1 || true
ufw allow 443/tcp >/dev/null 2>&1 || true
ufw --force enable >/dev/null 2>&1 || true

# --- Keep-alive + weekly channel refresh (cron) ---------------------------
# Hourly local health check (keeps the instance from looking idle) and a
# weekly iptv-org import that only updates channels.json (it does NOT
# delete the database, so admin codes are safe; to apply a refresh,
# delete openlive.db and restart — see ORACLE_DEPLOY.md).
cat > /etc/cron.d/openlive <<EOF
# OpenLive keep-alive: hourly health check, weekly channel-list refresh.
17 * * * * ubuntu curl -fsS http://127.0.0.1:8000/api/health >/dev/null 2>&1
30 3 * * 0 ubuntu cd $BACKEND_DIR && $BACKEND_DIR/.venv/bin/python scripts/import_iptv_org.py --max 250 >> /var/log/openlive-import.log 2>&1
EOF
chmod 644 /etc/cron.d/openlive

# --- 8. Health check -------------------------------------------------------
echo "[7/7] Checking the backend..."
sleep 3
if curl -fsS http://127.0.0.1:8000/api/health; then
    echo
    echo "OpenLive is up."
else
    echo "WARNING: the backend did not answer on 127.0.0.1:8000." >&2
    echo "Check: sudo journalctl -u openlive -n 50" >&2
fi

echo
echo "Public URL (put this in the app Settings): $PUBLIC_URL"
if [ "$TOKEN_JUST_CREATED" -eq 1 ]; then
    echo
    echo "ADMIN TOKEN (save this — it is shown only here, and lives in $ENV_FILE):"
    echo "  $(grep OPENLIVE_ADMIN_TOKEN "$ENV_FILE" | cut -d= -f2)"
    echo "Never commit it or share it in chat."
fi
